(function floatingParticles() {
  const canvas = document.getElementById('particlesCanvas');
  if (!canvas || prefersReducedMotion) return;

  const ctx = canvas.getContext('2d');
  const isMobile = window.matchMedia('(max-width: 700px)').matches;
  const COUNT = isMobile ? 22 : 46;

  let width, height, particles, raf, running = false;

  function makeParticle() {
    return {
      x: Math.random() * width,
      y: Math.random() * height,
      r: Math.random() * 1.6 + 0.6,
      speed: Math.random() * 0.25 + 0.08,
      drift: (Math.random() - 0.5) * 0.15,
      alpha: Math.random() * 0.35 + 0.12,
    };
  }

  function init() {
    width = canvas.width = window.innerWidth;
    height = canvas.height = window.innerHeight;
    particles = Array.from({ length: COUNT }, makeParticle);
  }

  function tick() {
    ctx.clearRect(0, 0, width, height);
    particles.forEach(p => {
      p.y -= p.speed;
      p.x += p.drift;

      if (p.y < -10) { p.y = height + 10; p.x = Math.random() * width; }
      if (p.x < -10) p.x = width + 10;
      if (p.x > width + 10) p.x = -10;

      ctx.beginPath();
      ctx.arc(p.x, p.y, p.r, 0, Math.PI * 2);
      ctx.fillStyle = `rgba(167, 139, 250, ${p.alpha})`;
      ctx.fill();
    });
    if (running) raf = requestAnimationFrame(tick);
  }

  function start() {
    if (running) return;
    running = true;
    raf = requestAnimationFrame(tick);
  }
  function stop() {
    running = false;
    cancelAnimationFrame(raf);
  }

  init();
  start();

  window.addEventListener('resize', init);

  // pausa quando a aba não está visível — economiza CPU/bateria
  document.addEventListener('visibilitychange', () => {
    if (document.hidden) stop();
    else start();
  });
})();

// ---------- Terminal com efeito de digitação ----------
function getTerminalLines() {
  const t = i18n[currentLang];
  return [
    { prompt: 'luana@dev:~$', text: ' whoami', after: t['terminal.whoami'] },
    { prompt: 'luana@dev:~$', text: ' cat foco.txt', after: t['terminal.foco'] },
    { prompt: 'luana@dev:~$', text: ' ls ferramentas/', after: t['terminal.ferramentas'] },
  ];
}

function typeTerminal(container) {
  const terminalLines = getTerminalLines();
  let lineIndex = 0;

  function typeNextLine() {
    if (lineIndex >= terminalLines.length) {
      const finalLine = document.createElement('div');
      finalLine.className = 'term-line';
      finalLine.innerHTML = `<span class="prompt">luana@dev:~$</span> <span class="cursor"></span>`;
      container.appendChild(finalLine);
      return;
    }

    const { prompt, text, after } = terminalLines[lineIndex];
    const cmdLine = document.createElement('div');
    cmdLine.className = 'term-line';
    const promptSpan = document.createElement('span');
    promptSpan.className = 'prompt';
    promptSpan.textContent = prompt;
    const typedSpan = document.createElement('span');
    cmdLine.appendChild(promptSpan);
    cmdLine.appendChild(typedSpan);
    container.appendChild(cmdLine);

    let charIndex = 0;
    const typeChar = setInterval(() => {
      typedSpan.textContent += text[charIndex];
      charIndex++;
      if (charIndex >= text.length) {
        clearInterval(typeChar);
        const afterLine = document.createElement('div');
        afterLine.className = 'term-line';
        afterLine.textContent = after;
        container.appendChild(afterLine);
        lineIndex++;
        setTimeout(typeNextLine, 350);
      }
    }, 35);
  }

  typeNextLine();
}

const terminalEl = document.getElementById('labTerminal');
if (terminalEl) {
  if (prefersReducedMotion) {
    getTerminalLines().forEach(({ prompt, text, after }) => {
      const cmdLine = document.createElement('div');
      cmdLine.className = 'term-line';
      cmdLine.innerHTML = `<span class="prompt">${prompt}</span>${text}`;
      terminalEl.appendChild(cmdLine);
      const afterLine = document.createElement('div');
      afterLine.className = 'term-line';
      afterLine.textContent = after;
      terminalEl.appendChild(afterLine);
    });
    const finalLine = document.createElement('div');
    finalLine.className = 'term-line';
    finalLine.innerHTML = `<span class="prompt">luana@dev:~$</span> _`;
    terminalEl.appendChild(finalLine);
  } else {
    const terminalObserver = new IntersectionObserver((entries) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          typeTerminal(terminalEl);
          terminalObserver.unobserve(entry.target);
        }
      });
    }, { threshold: 0.4 });
    terminalObserver.observe(terminalEl);
  }
}

