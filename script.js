const revealEls = document.querySelectorAll('.reveal');

function elementNearViewport(el, buffer = 60) {
  const rect = el.getBoundingClientRect();
  return rect.top < (window.innerHeight - buffer) && rect.bottom > 0;
}

function checkReveals() {
  revealEls.forEach(el => {
    if (!el.classList.contains('is-visible') && elementNearViewport(el)) {
      el.classList.add('is-visible');
    }
  });
}

if (prefersReducedMotion) {
  revealEls.forEach(el => el.classList.add('is-visible'));
} else {
  checkReveals(); // revela o que já estiver visível assim que a página carrega

  let revealTicking = false;
  window.addEventListener('scroll', () => {
    if (revealTicking) return;
    revealTicking = true;
    requestAnimationFrame(() => {
      checkReveals();
      revealTicking = false;
    });
  });
  window.addEventListener('resize', checkReveals);
  window.addEventListener('bootDone', checkReveals);
}

