(function commandPalette() {
  const overlay = document.getElementById('cmdk');
  const input = document.getElementById('cmdkInput');
  const output = document.getElementById('cmdkOutput');
  const trigger = document.getElementById('cmdkTrigger');
  if (!overlay || !input || !output) return;

  function open() {
    overlay.classList.add('open');
    input.value = '';
    input.focus();
  }
  function close() {
    overlay.classList.remove('open');
  }

  document.addEventListener('keydown', (e) => {
    const typing = ['INPUT', 'TEXTAREA'].includes(document.activeElement.tagName);
    if (e.key === '/' && !typing) {
      e.preventDefault();
      open();
    } else if (e.key === 'Escape') {
      close();
    }
  });

  trigger.addEventListener('click', open);
  overlay.addEventListener('click', (e) => { if (e.target === overlay) close(); });

  const commands = {
    help: () => 'comandos: projetos · aprendizado · curriculo · contato · skills · whoami · github · linkedin · tema · idioma · sudo hire luana · clear',
    projetos: () => { location.hash = '#projects'; close(); return 'navegando para #projects...'; },
    projects: () => commands.projetos(),
    aprendizado: () => { location.hash = '#learning'; close(); return 'navegando para #learning...'; },
    learning: () => commands.aprendizado(),
    curriculo: () => { location.hash = '#cv'; close(); return 'navegando para #cv...'; },
    cv: () => commands.curriculo(),
    contato: () => { location.hash = '#contact'; close(); return 'navegando para #contact...'; },
    contact: () => commands.contato(),
    skills: () => 'HTML5 · CSS3 · JavaScript · TypeScript · Angular · Node.js · PHP · Python · Nuxt · Git',
    whoami: () => 'luana gimenes dos santos · full stack em formação',
    github: () => { window.open('https://github.com/luanagimns', '_blank'); return 'abrindo github.com/luanagimns ↗'; },
    linkedin: () => { window.open('https://www.linkedin.com/in/luanagimns/', '_blank'); return 'abrindo linkedin ↗'; },
    tema: () => { document.getElementById('themeToggle').click(); return 'tema alternado.'; },
    theme: () => commands.tema(),
    idioma: () => { setLanguage(currentLang === 'pt' ? 'en' : 'pt'); return 'idioma alternado.'; },
    language: () => commands.idioma(),
    'sudo hire luana': () => { location.hash = '#contact'; close(); return 'permissão concedida. redirecionando...'; },
    clear: () => { output.innerHTML = ''; return null; },
    exit: () => { close(); return null; },
  };

  input.addEventListener('keydown', (e) => {
    if (e.key !== 'Enter') return;
    const raw = input.value.trim();
    if (!raw) return;
    const line = document.createElement('div');
    line.className = 'cmdk-line';
    line.innerHTML = `<span class="cmdk-prompt">$</span> ${raw}`;
    output.appendChild(line);

    const fn = commands[raw.toLowerCase()];
    const result = fn ? fn() : `comando não encontrado: ${raw} — digite "help"`;
    if (result) {
      const res = document.createElement('div');
      res.className = 'cmdk-result';
      res.textContent = result;
      output.appendChild(res);
    }
    output.scrollTop = output.scrollHeight;
    input.value = '';
  });
})();

