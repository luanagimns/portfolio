// ---------- Botões magnéticos + ripple effect ----------
(function magneticButtons() {
  const hasFinePointer = window.matchMedia('(pointer: fine)').matches;

  document.querySelectorAll('.btn.fill, .btn.ghost').forEach(btn => {
    if (hasFinePointer && !prefersReducedMotion) {
      btn.addEventListener('mousemove', (e) => {
        const rect = btn.getBoundingClientRect();
        const x = e.clientX - rect.left - rect.width / 2;
        const y = e.clientY - rect.top - rect.height / 2;
        btn.style.transform = `translate(${x * 0.15}px, ${y * 0.3}px)`;
      });
      btn.addEventListener('mouseleave', () => { btn.style.transform = ''; });
    }

    btn.addEventListener('click', (e) => {
      const rect = btn.getBoundingClientRect();
      const size = Math.max(rect.width, rect.height) * 1.6;
      const ripple = document.createElement('span');
      ripple.className = 'ripple';
      ripple.style.width = ripple.style.height = size + 'px';
      ripple.style.left = (e.clientX - rect.left - size / 2) + 'px';
      ripple.style.top = (e.clientY - rect.top - size / 2) + 'px';
      btn.appendChild(ripple);
      ripple.addEventListener('animationend', () => ripple.remove());
    });
  });
})();

// ---------- Hover 3D tilt nos cards de projeto ----------
(function tiltCards() {
  const hasFinePointer = window.matchMedia('(pointer: fine)').matches;
  if (!hasFinePointer || prefersReducedMotion) return;

  let isPressing = false;
  document.addEventListener('mousedown', () => { isPressing = true; });
  document.addEventListener('mouseup', () => { isPressing = false; });

  document.querySelectorAll('.tilt-card').forEach(card => {
    // glow que segue o cursor
    const glow = document.createElement('div');
    glow.className = 'tilt-glow';
    card.appendChild(glow);

    const maxTilt = 7; // graus

    card.addEventListener('mousemove', (e) => {
      if (isPressing) return;
      const rect = card.getBoundingClientRect();
      const px = (e.clientX - rect.left) / rect.width;  // 0..1
      const py = (e.clientY - rect.top) / rect.height;  // 0..1

      const rotateY = (px - 0.5) * maxTilt * 2;
      const rotateX = (0.5 - py) * maxTilt * 2;

      card.style.transform = `rotateX(${rotateX}deg) rotateY(${rotateY}deg) translateZ(0) scale(1.015)`;
      card.style.setProperty('--mx', `${px * 100}%`);
      card.style.setProperty('--my', `${py * 100}%`);
    });

    card.addEventListener('mouseleave', () => {
      card.style.transform = '';
    });
  });
})();

// ---------- Filtro interativo de projetos por tag ----------
(function projectFilter() {
  const chips = document.querySelectorAll('.filter-chip');
  const items = document.querySelectorAll('#projGrid .proj-item');
  const empty = document.getElementById('filterEmpty');
  if (!chips.length) return;

  chips.forEach(chip => {
    chip.addEventListener('click', () => {
      chips.forEach(c => c.classList.remove('active'));
      chip.classList.add('active');
      const filter = chip.dataset.filter;

      let visibleCount = 0;
      items.forEach(item => {
        const match = filter === 'ALL' || item.dataset.tag === filter;
        item.classList.toggle('filtered-out', !match);
        if (match) visibleCount++;
      });

      if (empty) empty.style.display = visibleCount === 0 ? 'block' : 'none';
    });
  });
})();

