(function contactEmailFallback() {
  const btn = document.getElementById('contactEmailBtn');
  const status = document.getElementById('contactCopied');
  if (!btn || !status) return;

  let hideTimeout;

  btn.addEventListener('click', async () => {
    if (!navigator.clipboard) return;
    try {
      await navigator.clipboard.writeText('byluanagimenes@gmail.com');
      status.textContent = i18n[currentLang]['contact.copied'];
      status.classList.add('is-visible');
      clearTimeout(hideTimeout);
      hideTimeout = setTimeout(() => status.classList.remove('is-visible'), 4000);
    } catch (err) {
      // clipboard indisponível (ex: contexto não seguro) — o mailto: segue como único caminho
    }
  });
})();

